@dataclass
class QueryExpander:
    """질의 확장기. 사전은 테넌트별로 교체 가능하다."""

    lexicon: dict[str, tuple[str, ...]] | None = None
    max_expansions: int = MAX_EXPANSIONS
    enabled: bool = True

    def __post_init__(self) -> None:
        self._lexicon = DEFAULT_LEXICON if self.lexicon is None else self.lexicon

    def expand(self, query: str) -> tuple[str, list[str]]:
        """``(확장된 질의, 덧붙인 용어)``.

        덧붙인 용어를 함께 돌려주는 이유: 튜닝 콘솔이 "왜 이 조항이 1위인가"를
        설명하려면 확장 여부를 알아야 한다. 숨기면 콘솔이 거짓말을 한다.
        """
        if not self.enabled or not query.strip():
            return query, []

        added: list[str] = []
        for trigger, terms in self._lexicon.items():
            if trigger not in query:
                continue
            for term in terms:
                # 이미 질의에 있는 말을 다시 넣으면 그 토큰만 두 배로 세어져
                # 가중치가 왜곡된다.
                if term in query or term in added:
                    continue
                added.append(term)
                if len(added) >= self.max_expansions:
                    return f"{query} {' '.join(added)}", added

        if not added:
            return query, []
        return f"{query} {' '.join(added)}", added
