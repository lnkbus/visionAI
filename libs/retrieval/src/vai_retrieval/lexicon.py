"""구어 → 약관 용어 질의 확장.

고객은 약관의 말로 묻지 않는다. 약관은 "분실"이라 쓰지만 고객은 "카드
잃어버렸어요"라고 말한다. 두 표현은 **문자가 하나도 겹치지 않아** 어휘 기반
검색(BM25·해싱 임베딩)에서는 서로를 전혀 찾지 못한다. 의미 임베딩 모델이 붙으면
상당 부분 흡수되지만, 폐쇄망 최소 구성(모델 없음)에서는 이 층이 유일한 다리다.

설계에서 정한 것들:

* **질의 시점에만 확장한다.** 색인 시점에 넣으면 BM25 문서빈도가 통째로 바뀌어
  사전을 한 줄 고칠 때마다 전체 재색인이 필요해진다. 사전은 자주 고쳐진다.
* **원문을 지우지 않고 덧붙인다.** 고객이 "분실"이라고 정확히 말하는 경우도
  많고, 그때 원래 신호를 잃으면 손해다.
* **추가 항목 수에 상한을 둔다.** 확장어가 많아질수록 질의 벡터가 평균으로
  끌려가 변별력이 떨어진다 — 다 넣는 것이 항상 좋은 것은 아니다.
* **리랭킹에는 원문 질의를 넘긴다.** 크로스 인코더는 자연스러운 문장을 전제로
  학습됐다. 확장으로 부풀린 문자열을 주면 오히려 판단이 흐려진다.

.. warning::
   기본 사전은 카드 상담 어휘를 기준으로 작성한 **출발점**이다. 사업별로
   고객이 쓰는 말은 다르다(카드/보험/통신). 실제 상담 로그로 검증하고 테넌트
   사전으로 덮어쓰는 것을 전제로 한다 — 골든셋 점수가 올랐다는 것만으로
   현장에서 오른다고 말할 수 없다.
"""

